#Блок №1. Абсолютная и относительная погрешность

print("--- Задание №1 ---")
pairs = [
    ("1. x=3,14 (π)", 3.14, math.pi),
    ("2. x=2,718 (e)", 2.718, math.e),
    ("3. x=9,8 (g)", 9.8, 9.81),
    ("4. x=0,333 (1/3)", 0.333, 1/3)
]

results = []
for name, approx, exact in pairs:
    delta = abs(approx - exact)
    rel = (delta / abs(exact)) * 100
    results.append((name, delta, rel))
    print(f"{name:<20} Δx = {delta:.6f},  δx = {rel:.4f}%")

print("\nСортировка по Δx (абсолютная):")
for r in sorted(results, key=lambda x: x[1]):
    print(f"  {r[0]}")

print("\nСортировка по δx (относительная):")
for r in sorted(results, key=lambda x: x[2]):
    print(f"  {r[0]}")

print("\nВывод к задаче 1:")
print("По абсолютной погрешности лучшая пара — 3,14 (Δ≈0.0016), худшая - 9,8 (Δ=0.01).")
print("По относительной погрешности лучшая тоже 3,14 (0.05%), а худшая - 2,718 (0.09%).")
print("Порядок примерно совпадает, так как точные значения сопоставимы по масштабу.\n")

